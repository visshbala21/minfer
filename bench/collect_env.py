"""Record the hardware and software environment into bench/ENV.md.

Every benchmark number in this repo is only meaningful next to the environment that
produced it, so ENV.md is generated by this script rather than written by hand.

Usage: python bench/collect_env.py
"""

from __future__ import annotations

import json
import platform
import subprocess
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENVS = {"minfer": ".venv", "vLLM": ".venv-vllm", "SGLang": ".venv-sglang"}
PACKAGES = [
    "minfer",
    "vllm",
    "sglang",
    "torch",
    "triton",
    "flashinfer-python",
    "transformers",
    "tokenizers",
    "safetensors",
    "numpy",
    "xgrammar",
    "fastapi",
    "uvicorn",
]

_PROBE = """
import importlib.metadata as md, json, sys
out = {"python": sys.version.split()[0]}
for name in json.loads(sys.argv[1]):
    try:
        out[name] = md.version(name)
    except md.PackageNotFoundError:
        out[name] = None
try:
    import torch
    out["torch_build"] = torch.__version__
    out["torch_cuda"] = torch.version.cuda
    out["cudnn"] = str(torch.backends.cudnn.version())
except Exception as exc:  # torch missing or broken in this env
    out["torch_build"] = f"unavailable ({exc})"
print(json.dumps(out))
"""


def run(cmd: list[str]) -> str:
    """Run a command and return stripped stdout ('' on failure)."""
    try:
        return subprocess.run(cmd, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def probe_env(venv: Path) -> dict[str, str | None]:
    """Query package versions from inside a virtualenv."""
    python = venv / "bin" / "python"
    if not python.exists():
        return {}
    raw = run([str(python), "-c", _PROBE, json.dumps(PACKAGES)])
    return json.loads(raw.splitlines()[-1]) if raw else {}


def gpu_rows() -> list[list[str]]:
    """One row per GPU: index, name, memory, driver."""
    fields = "index,name,memory.total,driver_version"
    raw = run(["nvidia-smi", f"--query-gpu={fields}", "--format=csv,noheader"])
    return [[c.strip() for c in line.split(",")] for line in raw.splitlines() if line.strip()]


def cpu_model() -> str:
    """CPU model string from /proc/cpuinfo."""
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown"


def main() -> None:
    """Collect everything and write bench/ENV.md."""
    lines: list[str] = ["# Benchmark environment", ""]
    lines.append(
        f"Generated by `bench/collect_env.py` on {datetime.now(UTC):%Y-%m-%d %H:%M UTC}. "
        "Do not edit by hand."
    )
    lines += ["", "## Hardware", ""]
    gpus = gpu_rows()
    lines += ["| GPU | Name | Memory | Driver |", "|---|---|---|---|"]
    lines += [f"| {g[0]} | {g[1]} | {g[2]} | {g[3]} |" for g in gpus]
    smi = run(["nvidia-smi"])
    driver_cuda = next(
        (tok for line in smi.splitlines() if "CUDA Version" in line for tok in [line]), ""
    )
    driver_cuda = driver_cuda.split("CUDA Version:")[-1].strip(" |") if driver_cuda else "unknown"
    nvcc = run(["nvcc", "--version"]).splitlines()
    mem_kb = next(
        (
            int(line.split()[1])
            for line in Path("/proc/meminfo").read_text().splitlines()
            if line.startswith("MemTotal")
        ),
        0,
    )
    lines += [
        "",
        f"- GPU count: {len(gpus)}",
        f"- CPU: {cpu_model()} ({run(['nproc'])} logical cores visible)",
        f"- RAM: {mem_kb / 1024**2:.0f} GiB",
        f"- OS: {platform.platform()}",
        f"- Max CUDA version supported by driver: {driver_cuda}",
        f"- System CUDA toolkit (nvcc, used for FlashInfer JIT): "
        f"{nvcc[-2].strip() if len(nvcc) >= 2 else 'not found'}",
        "",
        "## Software",
        "",
        "Three isolated virtualenvs (see `scripts/setup_envs.sh`).",
        "",
    ]
    probes = {label: probe_env(ROOT / venv) for label, venv in ENVS.items()}
    keys = ["python", "torch_build", "torch_cuda", "cudnn", *PACKAGES]
    lines += ["| Package | " + " | ".join(ENVS) + " |", "|---|" + "---|" * len(ENVS)]
    for key in keys:
        cells = [str(probes[label].get(key) or "—") for label in ENVS]
        if all(c == "—" for c in cells):
            continue
        lines.append(f"| {key} | " + " | ".join(cells) + " |")
    lines.append("")
    out = ROOT / "bench" / "ENV.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
